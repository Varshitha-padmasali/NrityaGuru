/**
 * DEVELOPMENT MOCK — NOT REAL DATA.
 *
 * Used only when NEXT_PUBLIC_USE_MOCK_API=true, so the UI can be built and
 * clicked through before the FastAPI backend exists. The app shows a banner
 * whenever this is active. Every name and sentence here is an obvious
 * placeholder: no traditional meanings, no reference images, no real model
 * output. Never enable this for a demo, report screenshot or evaluation.
 */
import { endpoints } from "./api-endpoints";
import { ApiError } from "@/types/api";

const NOW = () => new Date().toISOString();
const PLACEHOLDER = "[Mock placeholder — real text comes from the knowledge base]";

const references = [
  { id: 101, name: "Sample Mudra A (hold)", reference_type: "mudra" as const, description: PLACEHOLDER, mudra_ids: [1], image_url: null, max_duration_seconds: 5 },
  { id: 102, name: "Sample sequence A → B → C", reference_type: "sequence" as const, description: PLACEHOLDER, mudra_ids: [1, 2, 3], image_url: null, max_duration_seconds: 8 },
];

type MockSession = { session_id: number; reference_id: number; status: string; created_at: string; evaluated?: boolean };
const sessions = new Map<number, MockSession>();
let nextSessionId = 1;

function mockResult(session: MockSession) {
  const ref = references.find((r) => r.id === session.reference_id) ?? references[0];
  return {
    reference: { id: ref.id, name: ref.name },
    predictions: [{ label: "Sample Mudra A", confidence: 0.5, frame_start: 0, frame_end: 59 }],
    dtw: { distance: 1, normalized: null, path_length: 60 },
    frames_total: 60,
    frames_with_landmarks: 54,
    fps: 30,
    deviations: [
      { kind: "insufficient_landmarks", message: "[Mock] Example deviation message.", frame_start: 20, frame_end: 26, expected_label: null, predicted_label: null },
    ],
    warnings: ["These are mock values generated by the frontend, not an evaluation."],
    model_version: "mock",
    feature_schema: "mock",
    created_at: NOW(),
  };
}

export async function handleMockRequest(method: string, path: string, body: unknown): Promise<unknown> {
  await new Promise((r) => setTimeout(r, 300));
  const pathWithoutQuery = path.split("?", 1)[0];

  if (path === endpoints.health()) return { status: "ok", db: "ok", model_loaded: false };
  if (pathWithoutQuery === endpoints.mudras()) return [];

  const mudraMatch = pathWithoutQuery.match(/^\/api\/mudras\/(.+)$/);
  if (mudraMatch) {
    throw new ApiError("not_found", "not found", 404, "The mock API has no knowledge catalogue. Connect the backend to view mudra records.");
  }

  if (path === endpoints.retrieve()) {
    const text = String((body as { text?: string })?.text ?? "");
    const words = text.split(/\W+/).filter((w) => w.length > 3).slice(0, 4);
    return {
      original_text: text,
      include_unverified: false,
      include_keyword_matches: false,
      supported_count: 0,
      unsupported_count: words.length,
      warnings: ["Mock mode has no knowledge catalogue."],
      disclaimer: "Mock response; connect the backend for sourced knowledge.",
      concepts: words.map((w) => ({
        concept: { text: w.toLowerCase(), concept_type: "object" },
        status: "unsupported",
        references: [],
        contains_unverified: false,
        note: "Mock mode has no knowledge catalogue.",
      })),
    };
  }

  if (path === endpoints.explain()) {
    return {
      original_text: String((body as { text?: string })?.text ?? ""),
      tutor: {
        mode: "knowledge_only",
        explanation: { summary: "Mock mode has no knowledge catalogue to explain.", concepts: [], suggestions: [], alternatives: [], source_ids: [], limitations: ["Connect the backend for sourced explanations."] },
        model: null,
        fallback_reason: "no_references",
        notice: "Mock response; no traditional meanings were supplied.",
      },
      retrieval: { concepts: [] },
      disclaimer: "Mock response; connect the backend for sourced knowledge.",
    };
  }

  if (path === endpoints.practiceReferences()) return references;

  if (path === endpoints.sessions() && method === "POST") {
    const refId = Number((body as { reference_id?: number })?.reference_id);
    const s: MockSession = { session_id: nextSessionId++, reference_id: refId, status: "created", created_at: NOW() };
    sessions.set(s.session_id, s);
    return s;
  }

  const sessionMatch = path.match(/^\/api\/practice\/sessions\/(\d+)\/(video|evaluate|results|feedback)$/);
  if (sessionMatch) {
    const s = sessions.get(Number(sessionMatch[1]));
    if (!s) throw new ApiError("not_found", "not found", 404, "Practice session not found (mock sessions reset on page reload)");
    switch (sessionMatch[2]) {
      case "video":
        s.status = "uploaded";
        return s;
      case "evaluate":
        s.status = "evaluated";
        s.evaluated = true;
        return { session_id: s.session_id, status: "evaluated", result: mockResult(s), error: null };
      case "results":
        return { session: s, result: s.evaluated ? mockResult(s) : null, feedback: null };
      case "feedback":
        return { text: "[Mock] Gemini feedback generated from the evaluation evidence will appear here.", model_name: "mock", created_at: NOW() };
    }
  }

  if (path === endpoints.progress()) {
    return {
      scope: "shared_development",
      sessions: [...sessions.values()].map((s) => ({
        session_id: s.session_id,
        reference_id: s.reference_id,
        reference_name: references.find((r) => r.id === s.reference_id)?.name ?? "Unknown",
        status: s.status,
        created_at: s.created_at,
        dtw_normalized: null,
        top_label: s.evaluated ? "Sample Mudra A" : null,
        top_confidence: s.evaluated ? 0.5 : null,
        feedback_summary: null,
      })),
    };
  }

  throw new ApiError("not_found", "not found", 404, `Mock API has no handler for ${method} ${path}`);
}
